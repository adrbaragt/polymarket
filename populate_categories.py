def ensure_table(cur):
    cur.execute("""
    BEGIN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE PMKT.MARKET_CATEGORY (
                category_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                parent_id     NUMBER REFERENCES PMKT.MARKET_CATEGORY(category_id),
                name          VARCHAR2(200) NOT NULL,
                depth         NUMBER NOT NULL,
                CONSTRAINT uk_market_category_name UNIQUE (name, parent_id)
            )
        ]';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -00955 THEN
                RAISE;
            END IF;
    END;
    """)

def get_or_create_category(cur, name, parent_name=None):
    """
    Return (category_id, depth) for given name/parent_name.
    Inserts if missing.
    parent_name is None for top-level.
    """
    # Determine parent_id and parent_depth
    parent_id = None
    parent_depth = -1  # so that depth = parent_depth + 1 = 0 for top-level
    if parent_name is not None:
        cur.execute(
            "SELECT category_id, depth FROM PMKT.MARKET_CATEGORY WHERE name = :name",
            {"name": parent_name}
        )
        row = cur.fetchone()
        if row is None:
            # Parent not yet inserted; we will insert it later (but we assume order)
            # For safety, insert parent now with depth 0 (will be corrected later if needed)
            parent_id = get_or_create_category(cur, parent_name, None)[0]
            parent_depth = 0  # placeholder; will be updated after
        else:
            parent_id, parent_depth = row
    # Check if this category already exists under this parent
    if parent_id is None:
        cur.execute(
            "SELECT category_id, depth FROM PMKT.MARKET_CATEGORY WHERE name = :name AND parent_id IS NULL",
            {"name": name}
        )
    else:
        cur.execute(
            "SELECT category_id, depth FROM PMKT.MARKET_CATEGORY WHERE name = :name AND parent_id = :parent_id",
            {"name": name, "parent_id": parent_id}
        )
    row = cur.fetchone()
    if row:
        return row  # (category_id, depth)
    # Insert new
    depth = parent_depth + 1
    out_id = cur.var(oracledb.NUMBER)
    cur.execute(
        """
        INSERT INTO PMKT.MARKET_CATEGORY (name, parent_id, depth)
        VALUES (:name, :parent_id, :depth)
        RETURNING category_id INTO :out_id
        """,
        {
            "name": name,
            "parent_id": parent_id,
            "depth": depth,
            "out_id": out_id
        }
    )
    val = out_id.getvalue()
    if isinstance(val, oracledb.Object):
        val = val.getvalue()
    return int(val[0]), depth

