def ensure_tables(cursor):
    # Hierarchical category table (used for the category_id static attribute)
    _create_table(
        cursor,
        """
        CREATE TABLE PMKT.MARKET_CATEGORY (
            category_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            parent_id   NUMBER REFERENCES PMKT.MARKET_CATEGORY(category_id),
            name        VARCHAR2(200) NOT NULL,
            depth       NUMBER NOT NULL,
            CONSTRAINT uk_market_category_name UNIQUE (name, parent_id)
        )
        """,
    )

    # Static market table
    _create_table(
        cursor,
        """
        CREATE TABLE PMKT.MARKET_PM (
            market_id      VARCHAR2(50) PRIMARY KEY,
            market_name    VARCHAR2(4000),
            close_date     TIMESTAMP,
            event_label    VARCHAR2(200),
            outcome_label  VARCHAR2(100),
            category_id    NUMBER REFERENCES PMKT.MARKET_CATEGORY(category_id)
        )
        """,
    )
    _add_column(cursor, "PMKT.MARKET_PM", "event_label VARCHAR2(200)")
    _add_column(cursor, "PMKT.MARKET_PM", "outcome_label VARCHAR2(100)")
    _add_column(cursor, "PMKT.MARKET_PM", "category_id NUMBER")

    # Time-varying observations table
    _create_table(
        cursor,
        """
        CREATE TABLE PMKT.MARKET_PM_OPTIES (
            optie_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            market_id       VARCHAR2(50) REFERENCES PMKT.MARKET_PM(market_id),
            prob_pct        NUMBER(5,2),
            extraction_date TIMESTAMP DEFAULT SYSTIMESTAMP,
            stability       NUMBER,
            liquidity       NUMBER
        )
        """,
    )
    _add_column(cursor, "PMKT.MARKET_PM_OPTIES", "stability NUMBER")
    _add_column(cursor, "PMKT.MARKET_PM_OPTIES", "liquidity NUMBER")

    _create_index(
        cursor,
        "IDX_MARKET_PM_CLOSE",
        "CREATE INDEX PMKT.IDX_MARKET_PM_CLOSE ON PMKT.MARKET_PM(close_date)",
    )
    _create_index(
        cursor,
        "IDX_OPTIES_MARKET",
        "CREATE INDEX PMKT.IDX_OPTIES_MARKET ON PMKT.MARKET_PM_OPTIES(market_id)",
    )


def get_or_create_category(cursor, cat_name, parent_name=None):
    """Return the category_id for a name, creating it under parent_name if needed."""
    if not cat_name:
        cat_name = "Uncategorized"
    cat_name = cat_name.strip()

    parent_id = None
    parent_depth = -1  # so a top-level category gets depth 0
    if parent_name:
        cursor.execute(
            "SELECT category_id, depth FROM PMKT.MARKET_CATEGORY "
            "WHERE name = :name AND parent_id IS NULL",
            {"name": parent_name},
        )
        row = cursor.fetchone()
        if row:
            parent_id, parent_depth = row
        else:
            parent_id = get_or_create_category(cursor, parent_name, None)
            parent_depth = 0

    if parent_id is None:
        cursor.execute(
            "SELECT category_id FROM PMKT.MARKET_CATEGORY "
            "WHERE name = :name AND parent_id IS NULL",
            {"name": cat_name},
        )
    else:
        cursor.execute(
            "SELECT category_id FROM PMKT.MARKET_CATEGORY "
            "WHERE name = :name AND parent_id = :parent_id",
            {"name": cat_name, "parent_id": parent_id},
        )
    row = cursor.fetchone()
    if row:
        return int(row[0])

    out_id = cursor.var(oracledb.NUMBER)
    cursor.execute(
        "INSERT INTO PMKT.MARKET_CATEGORY (name, parent_id, depth) "
        "VALUES (:name, :parent_id, :depth) "
        "RETURNING category_id INTO :out_id",
        {
            "name": cat_name,
            "parent_id": parent_id,
            "depth": parent_depth + 1,
            "out_id": out_id,
        },
    )
    val = out_id.getvalue()
    if isinstance(val, oracledb.Object):
        val = val.getvalue()
    return int(val[0])


def fetch_event_tags(event_id):
    """Fetch an event's tag slugs, cached by event id."""
    if not event_id:
        return []
    key = str(event_id)
    if key in _event_tag_cache:
        return _event_tag_cache[key]

    tags = []
    try:
        resp = requests.get(f"{EVENTS_API_BASE}/{key}", timeout=20)
        if resp.status_code == 200:
            data = resp.json()
            if isinstance(data, list):
                data = data[0] if data else {}
            for tag in data.get("tags") or []:
                slug = tag.get("slug") or tag.get("label") or ""
                slug = str(slug).strip().lower()
                if slug:
                    tags.append(slug)
    except Exception:
        tags = []

    _event_tag_cache[key] = tags
    return tags


def resolve_category(cursor, market):
    """
    Resolve a real category for a market.

    Returns (category_id, is_real). Market-level category fields are currently
    null, so the event's tags are used first. `is_real` is False only when the
    fallback "Uncategorized" bucket is used.
    """
    events = market.get("events")
    if isinstance(events, list) and events and isinstance(events[0], dict):
        tag_set = set(fetch_event_tags(events[0].get("id")))
        for slug, top, sub in CATEGORY_RULES:
            if slug in tag_set:
                return get_or_create_category(cursor, sub or top, top if sub else None), True

    cat_name = market.get("category")
    if not cat_name:
        cats = market.get("categories")
        if isinstance(cats, list) and cats:
            cat_name = cats[0]
    if cat_name:
        return get_or_create_category(cursor, str(cat_name)), True

    return get_or_create_category(cursor, "Uncategorized"), False


# ---------- Polymarket API helpers ----------
def fetch_markets_page(offset, end_date_min, end_date_max):
    params = {
        "closed": "false",
        "limit": PAGE_SIZE,
        "offset": offset,
        "end_date_min": end_date_min,
        "end_date_max": end_date_max,
    }
    try:
        resp = requests.get(API_BASE, params=params, timeout=20)
        if resp.status_code != 200:
            return []
        return resp.json()
    except Exception:
        return []


def get_price_history(token_id, start_ts, end_ts):
    """Fetch price history for an outcome token (asset_id) from the CLOB API."""
    params = {
        "market": token_id,
        "startTs": start_ts,
        "endTs": end_ts,
    }
    try:
        resp = requests.get(CLOB_PRICE_HISTORY_BASE, params=params, timeout=20)
        if resp.status_code != 200:
            return []
        data = resp.json()
        history = data.get("history", [])
        history.sort(key=lambda x: x["t"])
        return history
    except Exception:
        return []


# ---------- Metric ----------
def compute_stability_score(history, t0, T):
    """
    Stability score = 1 - NRMSD, where NRMSD is the RMS deviation between the
    observed price path and an ideal linear path from p(t0) to 1.0 at expiry T.
    Returns None if there is not enough data.
    """
    if len(history) < 2:
        return None
    if T <= t0:
        return None

    p0 = float(history[0]["p"])
    total_interval = T - t0
    sum_sq = 0.0
    count = 0
    for point in history:
        t = float(point["t"])
        p = float(point["p"])
        if t < t0 or t > T:
            continue
        ideal = p0 + (1.0 - p0) * (t - t0) / total_interval
        diff = p - ideal
        sum_sq += diff * diff
        count += 1

    if count == 0:
        return None

    rmsd = math.sqrt(sum_sq / count)
    max_dev = 1.0 - p0
    if max_dev <= 0:
        nrmsd = 0.0
    else:
        nrmsd = min(1.0, rmsd / max_dev)

    stability = 1.0 - nrmsd
    return max(0.0, min(1.0, stability))


# ---------- Parsing helpers ----------
def _as_list(value):
    """Return a list from either a JSON string or an existing list."""
    if value is None:
        return []
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
            return parsed if isinstance(parsed, list) else []
        except Exception:
            return []
    return value if isinstance(value, list) else []


def _parse_close_date(market):
    end_date_str = market.get("endDate")
    if not end_date_str:
        return None
    try:
        if end_date_str.endswith("Z"):
            end_date_str = end_date_str[:-1] + "+00:00"
        close_date = datetime.datetime.fromisoformat(end_date_str)
    except Exception:
        try:
            from dateutil import parser
            close_date = parser.isoparse(market.get("endDate"))
        except Exception:
            return None
    if close_date.tzinfo is not None:
        close_date = close_date.astimezone(datetime.timezone.utc).replace(tzinfo=None)
    return close_date


# ---------- Insertion helpers ----------
def insert_market_static(cursor, market, category_id, category_is_real=True):
    """Insert the static MARKET_PM row. Returns True if inserted, False if skipped."""
    market_id = str(market.get("id"))
    question = (market.get("question") or "")[:4000]
    close_date = _parse_close_date(market)
    if close_date is None:
        return False

    event_label = None
    events = market.get("events")
    if isinstance(events, list) and events:
        first_event = events[0]
        if isinstance(first_event, dict):
            event_label = first_event.get("title")
        elif isinstance(first_event, str):
            event_label = first_event

    # outcome_label: label of the outcome with the higher current price
    outcomes = _as_list(market.get("outcomes"))
    prices = _as_list(market.get("outcomePrices"))
    outcome_label = None
    if outcomes and prices:
        try:
            max_idx = max(range(len(prices)), key=lambda i: float(prices[i]))
            outcome_label = str(outcomes[max_idx]) if max_idx < len(outcomes) else None
        except Exception:
            outcome_label = None

    try:
        cursor.execute(
            """
            INSERT INTO PMKT.MARKET_PM
            (market_id, market_name, close_date, event_label, outcome_label, category_id)
            VALUES
            (:market_id, :market_name, :close_date, :event_label, :outcome_label, :category_id)
            """,
            {
                "market_id": market_id,
                "market_name": question,
                "close_date": close_date,
                "event_label": event_label,
                "outcome_label": outcome_label,
                "category_id": category_id,
            },
        )
        return True
    except oracledb.IntegrityError as e:
        if "ORA-00001" not in str(e):
            raise
        # Repair the category of a row that was stored before tag-based
        # resolution existed. Never downgrade a real category on transient
        # event-fetch failures.
        if category_is_real:
            cursor.execute(
                "UPDATE PMKT.MARKET_PM SET category_id = :category_id "
                "WHERE market_id = :market_id",
                {"category_id": category_id, "market_id": market_id},
            )
        return False  # already present


def insert_market_observation(cursor, market_id, prob_pct, stability, liquidity, extraction_dt):
    cursor.execute(
        """
        INSERT INTO PMKT.MARKET_PM_OPTIES
        (market_id, prob_pct, extraction_date, stability, liquidity)
        VALUES
        (:market_id, :prob_pct, :extraction_date, :stability, :liquidity)
        """,
        {
            "market_id": market_id,
            "prob_pct": prob_pct,
            "extraction_date": extraction_dt,
            "stability": stability,
            "liquidity": liquidity,
        },
    )


# ---------- Main ----------
def main():
    start_time = datetime.datetime.now(datetime.timezone.utc)
    now_ts = int(start_time.timestamp())
    extraction_dt = start_time.astimezone(datetime.timezone.utc).replace(tzinfo=None)

    print(f"Starting scan at {start_time.isoformat()}")
    print(f"Threshold: probability >= {PROBABILITY_THRESHOLD}% and <= {MAX_PROBABILITY}%")
    print(f"Lookahead: {LOOKAHEAD_DAYS} days")
    print(f"Exclude markets closing sooner than {SHORT_TERM_EXCLUDE_MINUTES} minutes")
    print(f"Stability metric uses price history window: {PRICE_HISTORY_DAYS} days")

    conn = None
    try:
        conn = get_connection()
        conn.autocommit = False
        cur = conn.cursor()
        ensure_tables(cur)

        # Incremental mode: do NOT truncate. New markets are inserted into
        # MARKET_PM (deduplicated on market_id), and every run appends a fresh
        # observation row into MARKET_PM_OPTIES.
        now = datetime.datetime.now(datetime.timezone.utc)
        max_close = now + datetime.timedelta(days=LOOKAHEAD_DAYS)
        min_close = now + datetime.timedelta(minutes=SHORT_TERM_EXCLUDE_MINUTES)

        end_date_min = now.strftime("%Y-%m-%dT%H:%M:%SZ")
        end_date_max = max_close.strftime("%Y-%m-%dT%H:%M:%SZ")

        inserted_static = 0
        inserted_opties = 0
        scanned = 0
        offset = 0

        while True:
            batch = fetch_markets_page(offset, end_date_min, end_date_max)
            if not batch:
                break
            scanned += len(batch)

            for m in batch:
                close_date = _parse_close_date(m)
                if close_date is None:
                    continue
                if close_date.tzinfo is None:
                    close_date = close_date.replace(tzinfo=datetime.timezone.utc)
                if close_date < min_close:
                    continue

                prices = _as_list(m.get("outcomePrices"))
                try:
                    prob = max([float(p) for p in prices]) if prices else 0.0
                except Exception:
                    prob = 0.0
                if prob * 100.0 < PROBABILITY_THRESHOLD or prob * 100.0 > MAX_PROBABILITY:
                    continue

                market_id = str(m.get("id"))

                # Category resolution (event tags -> MARKET_CATEGORY hierarchy)
                category_id, category_is_real = resolve_category(cur, m)

                # Insert static row (dedup on market_id)
                if insert_market_static(cur, m, category_id, category_is_real):
                    inserted_static += 1

                # Resolve the token for the higher-priced outcome
                outcomes = _as_list(m.get("outcomes"))
                token_ids = _as_list(m.get("clobTokenIds"))
                higher_idx = None
                if token_ids and len(token_ids) == len(outcomes) and prices:
                    try:
                        higher_idx = max(range(len(prices)), key=lambda i: float(prices[i]))
                    except Exception:
                        higher_idx = None

                stability = None
                liquidity = None
                if higher_idx is not None and 0 <= higher_idx < len(token_ids):
                    token_id = str(token_ids[higher_idx])
                    end_ts = now_ts
                    start_ts = end_ts - PRICE_HISTORY_DAYS * 86400
                    history = get_price_history(token_id, start_ts, end_ts)
                    if history:
                        t0 = float(history[0]["t"])
                        T = float(close_date.timestamp())
                        stability = compute_stability_score(history, t0, T)

                # Liquidity from the market metadata (USD amount)
                liquidity_str = m.get("liquidity")
                try:
                    liquidity = float(liquidity_str) if liquidity_str is not None else None
                except Exception:
                    liquidity = None

                insert_market_observation(
                    cur, market_id, prob * 100.0, stability, liquidity, extraction_dt
                )
                inserted_opties += 1

            conn.commit()
            offset += PAGE_SIZE
            print(
                f"  Offset {offset}: scanned {len(batch)} markets, "
                f"static rows {inserted_static}, opties rows {inserted_opties}"
            )
            if len(batch) < PAGE_SIZE:
                break

        elapsed = (datetime.datetime.now(datetime.timezone.utc) - start_time).total_seconds()
        print("\nScan finished.")
        print(f"  Markets scanned: {scanned}")
        print(f"  Static market rows inserted: {inserted_static}")
        print(f"  Observation rows inserted: {inserted_opties}")
        print(f"  Elapsed time: {elapsed:.1f}s")

    except Exception as e:
        print(f"Error: {e}")
        if conn:
            conn.rollback()
        raise
    finally:
        if conn:
            conn.close()


def fetch_market_by_id(market_id):
    """Fetch a single Gamma market by id."""
    try:
        resp = requests.get(API_BASE, params={"id": str(market_id)}, timeout=20)
        if resp.status_code != 200:
            return None
        data = resp.json()
        if isinstance(data, list):
            return data[0] if data else None
        return data if isinstance(data, dict) else None
    except Exception:
        return None


def backfill_categories():
    """Re-resolve categories for every row already in MARKET_PM."""
    conn = None
    try:
        conn = get_connection()
        cur = conn.cursor()

        # Make sure the hierarchy exists (and add Economics under Business).
        ensure_tables(cur)

        cur.execute("SELECT market_id FROM PMKT.MARKET_PM ORDER BY market_id")
        market_ids = [row[0] for row in cur.fetchall()]

        updated = 0
        unresolved = []
        for market_id in market_ids:
            market = fetch_market_by_id(market_id)
            if not market:
                unresolved.append((market_id, "market fetch failed"))
                continue

            category_id, is_real = resolve_category(cur, market)
            if not is_real:
                unresolved.append((market_id, "no matching event tag"))
                continue

            cur.execute(
                "UPDATE PMKT.MARKET_PM SET category_id = :category_id "
                "WHERE market_id = :market_id",
                {"category_id": category_id, "market_id": market_id},
            )
            if cur.rowcount:
                updated += 1

        conn.commit()
        print(f"Backfilled categories for {updated}/{len(market_ids)} markets.")
        if unresolved:
            print("Unresolved:")
            for market_id, reason in unresolved:
                print(f"  {market_id}: {reason}")
    except Exception:
        if conn:
            conn.rollback()
        raise
    finally:
        if conn:
            conn.close()


