def get_or_create_category(cursor, cat_name):
    """Return category_id for given name (top-level, parent_id NULL). Insert if missing."""
    if not cat_name:
        cat_name = "Uncategorized"
    cat_name = cat_name.strip()
    cursor.execute(
        "SELECT category_id FROM PMKT.MARKET_CATEGORY WHERE name = :name AND parent_id IS NULL",
        {"name": cat_name}
    )
    row = cursor.fetchone()
    if row:
        return row[0]
    out_id = cursor.var(oracledb.NUMBER)
    cursor.execute(
        """
        INSERT INTO PMKT.MARKET_CATEGORY (name, parent_id, depth)
        VALUES (:name, NULL, 0)
        RETURNING category_id INTO :out_id
        """,
        {"name": cat_name, "out_id": out_id}
    )
    val = out_id.getvalue()
    if isinstance(val, oracledb.Object):
        val = val.getvalue()
    return int(val[0])

def fetch_markets_page(offset, end_date_min, end_date_max):
    params = {
        "closed": "false",
        "limit": PAGE_SIZE,
        "offset": offset,
        "end_date_min": end_date_min,
        "end_date_max": end_date_max,
    }
    try:
        resp = requests.get(API_BASE, params=params, timeout=20)
        if resp.status_code != 200:
            return []
        return resp.json()
    except Exception:
        return []

def get_price_history(token_id, start_ts, end_ts):
    """Fetch price history for a token (asset_id) from CLOB API."""
    params = {
        "market": token_id,
        "startTs": start_ts,
        "endTs": end_ts,
    }
    try:
        resp = requests.get(CLOB_PRICE_HISTORY_BASE, params=params, timeout=20)
        if resp.status_code != 200:
            return []
        data = resp.json()
        # Expect {"history": [{"t": timestamp, "p": price}, ...]}
        history = data.get("history", [])
        # Ensure sorted by t
        history.sort(key=lambda x: x["t"])
        return history
    except Exception:
        return []

def compute_stability_score(history, p0_obs, t0, T):
    """
    Compute stability score based on deviation from ideal linear drift.
    history: list of dicts with keys 't' (unix timestamp) and 'p' (price 0-1)
    p0_obs: observed probability at t0 (should match history[0]['p'] approx)
    t0: start timestamp (int)
    T: end timestamp (int) expiry
    Returns score in [0,1] or None if insufficient data.
    """
    if len(history) < 2:
        return None
    if T <= t0:
        return None
    # Use observed p0 from first history point to avoid mismatch
    p0 = float(history[0]["p"])
    # If p0_obs provided, we could use it; but we'll use history p0.
    # Compute ideal line: p_ideal(t) = p0 + (1 - p0)*(t - t0)/(T - t0)
    total_interval = T - t0
    sum_sq = 0.0
    count = 0
    for point in history:
        t = float(point["t"])
        p = float(point["p"])
        if t < t0 or t > T:
            # skip points outside window (shouldn't happen if we filtered)
            continue
        ideal = p0 + (1.0 - p0) * (t - t0) / total_interval
        diff = p - ideal
        sum_sq += diff * diff
        count += 1
    if count == 0:
        return None
    rmsd = math.sqrt(sum_sq / count)
    # Normalize by max possible deviation (1 - p0)
    max_dev = 1.0 - p0
    if max_dev <= 0:
        nrmsd = 0.0
    else:
        nrmsd = rmsd / max_dev
        if nrmsd > 1:
            nrmsd = 1.0
    stability = 1.0 - nrmsd
    # Clamp
    if stability < 0:
        stability = 0.0
    if stability > 1:
        stability = 1.0
    return stability

def insert_market(cursor, market, now_ts):
    """Insert a single market record; computes stability score."""
    market_id = str(market.get("id"))
    question = market.get("question", "")[:4000]
    slug = market.get("slug")
    url = f"https://polymarket.com/market/{slug}" if slug else None

    # ---- Probability and outcome label ----
    outcome_prices_raw = market.get("outcomePrices", "[]")
    outcomes_raw = market.get("outcomes", "[]")
    try:
        prices = json.loads(outcome_prices_raw) if isinstance(outcome_prices_raw, str) else outcome_prices_raw
        outcomes = json.loads(outcomes_raw) if isinstance(outcomes_raw, str) else outcomes_raw
        if not isinstance(prices, list) or not isinstance(outcomes, list) or len(prices) == 0:
            prob = 0.0
            outcome_label = None
        else:
            max_idx = max(range(len(prices)), key=lambda i: float(prices[i]))
            prob = float(prices[max_idx])
            outcome_label = str(outcomes[max_idx]) if max_idx < len(outcomes) else None
    except Exception:
        prob = 0.0
        outcome_label = None

    probability_pct = prob * 100.0

    # ---- Close date ----
    end_date_str = market.get("endDate")
    try:
        if end_date_str.endswith('Z'):
            end_date_str = end_date_str[:-1] + '+00:00'
        close_date = datetime.datetime.fromisoformat(end_date_str)
    except Exception:
        try:
            from dateutil import parser
            close_date = parser.isoparse(market.get("endDate"))
        except Exception:
            close_date = None
    if close_date is None:
        return  # skip if we can't parse date
    if close_date.tzinfo is not None:
        close_date = close_date.astimezone(datetime.timezone.utc).replace(tzinfo=None)

    # ---- Category ----
    cat_str = market.get("category")
    if not cat_str:
        cats = market.get("categories")
        if isinstance(cats, list) and len(cats) > 0:
            cat_str = cats[0]
        else:
            cat_str = "Uncategorized"
    category_id = get_or_create_category(cursor, cat_str)

    # ---- Liquidity (USD amount) ----
    liquidity_str = market.get("liquidity")
    try:
        liquidity = float(liquidity_str) if liquidity_str is not None else None
    except Exception:
        liquidity = None

    # ---- Event label ----
    event_label = None
    events = market.get("events")
    if isinstance(events, list) and len(events) > 0:
        first_event = events[0]
        if isinstance(first_event, dict):
            event_label = first_event.get("title")
        elif isinstance(first_event, str):
            event_label = first_event

    # ---- Stability score ----
    stability_score = None
    # Determine token ID for the outcome with higher price (the one we used for prob)
    # We need to map outcome index to token ID from clobTokenIds
    clob_token_ids_raw = market.get("clobTokenIds", "[]")
    try:
        token_ids = json.loads(clob_token_ids_raw) if isinstance(clob_token_ids_raw, str) else clob_token_ids_raw
        if not isinstance(token_ids, list) or len(token_ids) < 2:
            token_ids = []
    except Exception:
        token_ids = []
    # Determine which token corresponds to higher price outcome
    # Assume token_ids order matches outcomes order (first token -> first outcome)
    higher_idx = None
    if len(token_ids) == len(outcomes) and len(outcomes) > 0:
        # recompute max idx just in case
        try:
            prices_list = json.loads(outcome_prices_raw) if isinstance(outcome_prices_raw, str) else outcome_prices_raw
            if isinstance(prices_list, list):
                higher_idx = max(range(len(prices_list)), key=lambda i: float(prices_list[i]))
            else:
                higher_idx = None
        except Exception:
            higher_idx = None
    else:
        higher_idx = None
    if higher_idx is not None and 0 <= higher_idx < len(token_ids):
        token_id = str(token_ids[higher_idx])
        # Fetch price history for last PRICE_HISTORY_DAYS days
        end_ts = int(now_ts)
        start_ts = end_ts - PRICE_HISTORY_DAYS * 86400
        history = get_price_history(token_id, start_ts, end_ts)
        if history:
            # Use first observed price from history as p0, t0 from first history point
            t0 = float(history[0]["t"])
            p0 = float(history[0]["p"])
            T = float(close_date.timestamp())
            stability_score = compute_stability_score(history, p0, t0, T)
        else:
            stability_score = None
    else:
        stability_score = None

    # ---- Insert ----
    cursor.execute(
        """
        INSERT INTO PMKT.POLYMARKET_MARKETS
        (market_id, question, url, probability_pct, outcome_label, event_label, liquidity, stability_score, close_date, category_id)
        VALUES
        (:market_id, :question, :url, :probability_pct, :outcome_label, :event_label, :liquidity, :stability_score, :close_date, :category_id)
        """,
        {
            "market_id": market_id,
            "question": question,
            "url": url,
            "probability_pct": probability_pct,
            "outcome_label": outcome_label,
            "event_label": event_label,
            "liquidity": liquidity,
            "stability_score": stability_score,
            "close_date": close_date,
            "category_id": category_id
        }
    )

def main():
    start_time = datetime.datetime.now(datetime.timezone.utc)
    now_ts = int(start_time.timestamp())
    print(f"Starting scan at {start_time.isoformat()}")
    print(f"Threshold: probability >= {PROBABILITY_THRESHOLD}% and <= {MAX_PROBABILITY}%")
    print(f"Lookahead: {LOOKAHEAD_DAYS} days")
    print(f"Exclude markets closing sooner than {SHORT_TERM_EXCLUDE_MINUTES} minutes")
    print(f"Using price history window: {PRICE_HISTORY_DAYS} days for stability metric")
    
    conn = None
    try:
        conn = get_connection()
        conn.autocommit = False
        cur = conn.cursor()
        ensure_tables(cur)
        # Truncate table to drop previous information
        try:
            cur.execute("TRUNCATE TABLE PMKT.POLYMARKET_MARKETS")
            conn.commit()
            print("Truncated PMKT.POLYMARKET_MARKETS")
        except Exception as e:
            conn.rollback()
            raise
        
        now = datetime.datetime.now(datetime.timezone.utc)
        max_close = now + datetime.timedelta(days=LOOKAHEAD_DAYS)
        min_close = now + datetime.timedelta(minutes=SHORT_TERM_EXCLUDE_MINUTES)
        
        end_date_min = now.strftime("%Y-%m-%dT%H:%M:%SZ")
        end_date_max = max_close.strftime("%Y-%m-%dT%H:%M:%SZ")
        
        inserted = 0
        scanned = 0
        offset = 0
        while True:
            batch = fetch_markets_page(offset, end_date_min, end_date_max)
            if not batch:
                break
            scanned += len(batch)
            for m in batch:
                end_str = m.get("endDate")
                try:
                    if end_str.endswith('Z'):
                        end_str = end_str[:-1] + '+00:00'
                    end_dt = datetime.datetime.fromisoformat(end_str)
                except Exception:
                    try:
                        from dateutil import parser
                        end_dt = parser.isoparse(m.get("endDate"))
                    except Exception:
                        continue
                if end_dt.tzinfo is None:
                    end_dt = end_dt.replace(tzinfo=datetime.timezone.utc)
                # Exclude short term (< min_close)
                if end_dt < min_close:
                    continue
                # probability check: lower bound and upper bound
                outcome_prices = m.get("outcomePrices", "[]")
                try:
                    prices = json.loads(outcome_prices) if isinstance(outcome_prices, str) else outcome_prices
                    if not isinstance(prices, list):
                        prices = []
                    prob = max([float(p) for p in prices]) if prices else 0.0
                except Exception:
                    prob = 0.0
                if prob * 100.0 < PROBABILITY_THRESHOLD or prob * 100.0 > MAX_PROBABILITY:
                    continue
                # Insert
                insert_market(cur, m, now_ts)
                inserted += 1
            conn.commit()
            offset += PAGE_SIZE
            print(f"  Offset {offset}: scanned {len(batch)} markets from this page, total inserted {inserted}")
            if len(batch) < PAGE_SIZE:
                break
        
        elapsed = (datetime.datetime.now(datetime.timezone.utc) - start_time).total_seconds()
        print(f"\nScan finished.")
        print(f"  Markets scanned: {scanned}")
        print(f"  Markets inserted: {inserted}")
        print(f"  Elapsed time: {elapsed:.1f}s")
        
    except Exception as e:
        print(f"Error: {e}")
        if conn:
            conn.rollback()
        raise
    finally:
        if conn:
            conn.close()

