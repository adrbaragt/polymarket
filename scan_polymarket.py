def get_connection():
    return oracledb.connect(user=DB_USER, password=DB_PASSWORD, dsn=DB_DSN)

def ensure_tables(cursor):
    # Create category table (hierarchical)
    cursor.execute("""
    BEGIN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE PMKT.MARKET_CATEGORY (
                category_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                parent_id     NUMBER REFERENCES PMKT.MARKET_CATEGORY(category_id),
                name          VARCHAR2(200) NOT NULL,
                depth         NUMBER NOT NULL,
                CONSTRAINT uk_market_category_name UNIQUE (name, parent_id)
            )
        ]';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -00955 THEN  -- ORA-00955: name is already used by an existing object
                RAISE;
            END IF;
    END;
    """)
    # Create market data table
    cursor.execute("""
    BEGIN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE PMKT.POLYMARKET_MARKETS (
                snapshot_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                market_id        VARCHAR2(50) NOT NULL,
                question         VARCHAR2(4000) NOT NULL,
                url              VARCHAR2(2000),
                probability_pct  NUMBER(5,2) NOT NULL,
                close_date       TIMESTAMP NOT NULL,
                category_id      NUMBER NOT NULL REFERENCES PMKT.MARKET_CATEGORY(category_id),
                extracted_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                raw_json         CLOB
            )
        ]';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -00955 THEN
                RAISE;
            END IF;
    END;
    """)
    # Optional index
    cursor.execute("""
    BEGIN
        EXECUTE IMMEDIATE 'CREATE INDEX PMKT.IDX_POLYMARKET_CLOSE ON PMKT.POLYMARKET_MARKETS(close_date)';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -00955 THEN  -- ORA-00955: name is already used by an existing object
                RAISE;
            END IF;
    END;
    """)

def get_or_create_category(cursor, cat_name):
    """Return category_id for given name (top-level, parent_id NULL). Insert if missing."""
    if not cat_name:
        cat_name = "Uncategorized"
    cat_name = cat_name.strip()
    # Try to find
    cursor.execute(
        "SELECT category_id FROM PMKT.MARKET_CATEGORY WHERE name = :name AND parent_id IS NULL",
        {"name": cat_name}
    )
    row = cursor.fetchone()
    if row:
        return row[0]
    out_id = cursor.var(oracledb.NUMBER)
    cursor.execute(
        """
        INSERT INTO PMKT.MARKET_CATEGORY (name, parent_id, depth)
        VALUES (:name, NULL, 0)
        RETURNING category_id INTO :out_id
        """,
        {"name": cat_name, "out_id": out_id}
    )
    val = out_id.getvalue()
    if isinstance(val, oracledb.Object):
        val = val.getvalue()
    return int(val[0])

def insert_market(cursor, market):
    """Insert a single market record; assumes category resolved."""
    market_id = str(market.get("id"))
    question = market.get("question", "")[:4000]
    slug = market.get("slug")
    url = f"https://polymarket.com/market/{slug}" if slug else None
    # probability: higher of outcomePrices
    outcome_prices = market.get("outcomePrices", "[]")
    try:
        prices = json.loads(outcome_prices) if isinstance(outcome_prices, str) else outcome_prices
        if not isinstance(prices, list):
            prices = []
        prob = max([float(p) for p in prices]) if prices else 0.0
    except Exception:
        prob = 0.0
    probability_pct = prob * 100.0
    # close date
    end_date_str = market.get("endDate")
    try:
        # Expect format like 2026-10-24T07:50:00Z
        # Make it offset-aware UTC
        if end_date_str.endswith('Z'):
            end_date_str = end_date_str[:-1] + '+00:00'
        close_date = datetime.datetime.fromisoformat(end_date_str)
    except Exception:
        # fallback: try parsing with dateutil if available
        try:
            from dateutil import parser
            close_date = parser.isoparse(market.get("endDate"))
        except Exception:
            close_date = None
    if close_date is None:
        # skip if we can't parse date
        return
    # Ensure timezone aware (convert to UTC naive for storage as TIMESTAMP)
    if close_date.tzinfo is not None:
        close_date = close_date.astimezone(datetime.timezone.utc).replace(tzinfo=None)
    # category
    cat_str = market.get("category")
    if not cat_str:
        cats = market.get("categories")
        if isinstance(cats, list) and len(cats) > 0:
            cat_str = cats[0]
        else:
            cat_str = "Uncategorized"
    category_id = get_or_create_category(cursor, cat_str)
    # raw json (optional)
    raw_json = json.dumps(market, ensure_ascii=False)
    # Insert
    cursor.execute(
        """
        INSERT INTO PMKT.POLYMARKET_MARKETS
        (market_id, question, url, probability_pct, close_date, category_id, raw_json)
        VALUES
        (:market_id, :question, :url, :probability_pct, :close_date, :category_id, :raw_json)
        """,
        {
            "market_id": market_id,
            "question": question,
            "url": url,
            "probability_pct": probability_pct,
            "close_date": close_date,
            "category_id": category_id,
            "raw_json": raw_json
        }
    )

def fetch_markets_page(offset):
    params = {
        "closed": "false",
        "limit": PAGE_SIZE,
        "offset": offset,
    }
    resp = requests.get(API_BASE, params=params, timeout=20)
    resp.raise_for_status()
    return resp.json()

def main():
    start_time = datetime.datetime.now(datetime.timezone.utc)
    print(f"Starting scan at {start_time.isoformat()}")
    print(f"Threshold: probability >= {PROBABILITY_THRESHOLD}%")
    print(f"Lookahead: {LOOKAHEAD_DAYS} days")
    print(f"Exclude markets closing sooner than {SHORT_TERM_EXCLUDE_MINUTES} minutes")
    
    conn = None
    try:
        conn = get_connection()
        conn.autocommit = False
        cur = conn.cursor()
        ensure_tables(cur)
        conn.commit()
        
        now = datetime.datetime.now(datetime.timezone.utc)
        max_close = now + datetime.timedelta(days=LOOKAHEAD_DAYS)
        min_close = now + datetime.timedelta(minutes=SHORT_TERM_EXCLUDE_MINUTES)
        
        inserted = 0
        scanned = 0
        offset = 0
        for page in range(MAX_PAGES):
            batch = fetch_markets_page(offset)
            if not batch:
                break
            scanned += len(batch)
            for m in batch:
                end_str = m.get("endDate")
                try:
                    if end_str.endswith('Z'):
                        end_str = end_str[:-1] + '+00:00'
                    end_dt = datetime.datetime.fromisoformat(end_str)
                except Exception:
                    try:
                        from dateutil import parser
                        end_dt = parser.isoparse(m.get("endDate"))
                    except Exception:
                        continue
                if end_dt.tzinfo is None:
                    end_dt = end_dt.replace(tzinfo=datetime.timezone.utc)
                # Apply lookahead window
                if end_dt < now or end_dt > max_close:
                    continue
                # Exclude short term
                if end_dt < min_close:
                    continue
                # probability check
                outcome_prices = m.get("outcomePrices", "[]")
                try:
                    prices = json.loads(outcome_prices) if isinstance(outcome_prices, str) else outcome_prices
                    if not isinstance(prices, list):
                        prices = []
                    prob = max([float(p) for p in prices]) if prices else 0.0
                except Exception:
                    prob = 0.0
                if prob * 100.0 < PROBABILITY_THRESHOLD:
                    continue
                # Insert
                insert_market(cur, m)
                inserted += 1
            conn.commit()
            offset += PAGE_SIZE
            print(f"  Page {page+1}: {len(batch)} markets scanned, total inserted {inserted}")
            if len(batch) < PAGE_SIZE:
                break  # no more data
        
        elapsed = (datetime.datetime.now(datetime.timezone.utc) - start_time).total_seconds()
        print(f"\nScan finished.")
        print(f"  Markets scanned: {scanned}")
        print(f"  Markets inserted: {inserted}")
        print(f"  Elapsed time: {elapsed:.1f}s")
        
    except Exception as e:
        print(f"Error: {e}")
        if conn:
            conn.rollback()
        raise
    finally:
        if conn:
            conn.close()

